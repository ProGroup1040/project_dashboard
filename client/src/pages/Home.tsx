const formatPhoneDisplay = (phone: string) => {
  // Convert international format to display format
  if (phone.startsWith("20")) {
    const local = "0" + phone.slice(2);
    return local.replace(/(\d{4})(\d{4})(\d{3})/, "$1 $2 $3");
  }
  return phone;
};

